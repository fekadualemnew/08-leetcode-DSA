class Solution:
    def moveZeroes(self, nums: list[int]) -> None:
        """
        Do not return anything, modify nums in-place instead.
        """
        n = len(nums)
        ptr = 0
        for i in range(n):
            if nums[i]:
                nums[ptr], nums[i] = nums[i], nums[ptr]
                ptr += 1
            

        